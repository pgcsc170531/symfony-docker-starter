use Symfony\Component\Console\Attribute\AsCommand;
use Symfony\Component\Console\Command\Command;
use Symfony\Component\Console\Input\InputInterface;
use Symfony\Component\Console\Output\OutputInterface;
use Symfony\Component\Console\Style\SymfonyStyle;
use Symfony\Component\DependencyInjection\Attribute\Autowire;

#[AsCommand(
    name: 'app:tenant:seed-nigeria',
    description: 'Seeds Nigerian Country, States, and LGAs into all tenant databases',
)]
class SeedNigeriaDataCommand extends Command
{
    public function __construct(
        #[Autowire(service: 'doctrine.orm.landlord_entity_manager')]
        private EntityManagerInterface $landlordEm,

        #[Autowire(env: 'LANDLORD_DATABASE_URL')]
        private string $databaseUrl
    ) {
        parent::__construct();
    }

    protected function execute(InputInterface $input, OutputInterface $output): int
    {
        $io = new SymfonyStyle($input, $output);
        $io->title('🇳🇬 Seeding Nigeria Data to All Tenants...');

        // 1. Get All Schools
        $schools = $this->landlordEm->getRepository(School::class)->findAll();
        
        // 2. Prepare Tenant Config
        $config = ORMSetup::createAttributeMetadataConfiguration(
            paths: [__DIR__ . '/../Entity/Tenant'],
            isDevMode: true
        );

        foreach ($schools as $school) {
            $io->section("Seeding: " . $school->getName());

            try {
                // Connect to Tenant DB
                $parts = parse_url($this->databaseUrl);
                $params = [
                    'user'     => $parts['user'],
                    'password' => $parts['pass'],
                    'host'     => $parts['host'],
                    'port'     => $parts['port'] ?? 3306,
                    'driver'   => 'pdo_mysql',
                    'dbname'   => $school->getDatabaseName(),
                ];

                $connection = DriverManager::getConnection($params, $config);
                $em = new \Doctrine\ORM\EntityManager($connection, $config);

                // --- BEGIN SEEDING LOGIC ---
                $this->seedNigeria($em, $io);
                // ---------------------------

                $connection->close();

            } catch (\Exception $e) {
                $io->error('❌ Failed: ' . $e->getMessage());
            }
        }

        $io->success('🎉 Nigeria Data Seeding Complete!');
        return Command::SUCCESS;
    }

    private function seedNigeria(\Doctrine\ORM\EntityManagerInterface $em, SymfonyStyle $io)
    {
        // 1. Create/Find Nigeria
        $countryRepo = $em->getRepository(Country::class);
        $nigeria = $countryRepo->findOneBy(['isoCode' => 'NG']);

        if (!$nigeria) {
            $nigeria = new Country();
            $nigeria->setName('Nigeria');
            $nigeria->setIsoCode('NG');
            $em->persist($nigeria);
            $em->flush();
            $io->text(" - Created Country: Nigeria");
        } else {
            $io->text(" - Country Nigeria already exists.");
        }

        // 2. The Big Data Array
        $nigerianStates = $this->getNigeriaData();

        foreach ($nigerianStates as $stateName => $lgas) {
            // Find or Create State
            $stateRepo = $em->getRepository(State::class);
            $state = $stateRepo->findOneBy(['name' => $stateName, 'country' => $nigeria]);

            if (!$state) {
                $state = new State();
                $state->setName($stateName);
                $state->setCountry($nigeria);
                $em->persist($state);
                $em->flush(); // Flush to get ID for LGAs
            }

            // Find or Create LGAs
            $lgaRepo = $em->getRepository(LGA::class);
            
            foreach ($lgas as $lgaName) {
                $existingLga = $lgaRepo->findOneBy(['name' => $lgaName, 'state' => $state]);
                
                if (!$existingLga) {
                    $lga = new LGA();
                    $lga->setName($lgaName);
                    $lga->setState($state);
                    $em->persist($lga);
                }
            }
            // Batch flush LGAs for this state
            $em->flush();
            $em->clear(); // Clear memory to prevent overflow
            
            // Re-fetch Nigeria for next loop since we cleared memory
            $nigeria = $em->getRepository(Country::class)->find($nigeria->getId());
        }
    }

